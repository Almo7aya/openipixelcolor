"""Generate firmware/src/drv/gamma_lut.c (8-bit gamma table from our own curve).

usage: python gen_gamma.py [gamma] > ../firmware/src/drv/gamma_lut.c
"""
import sys

g = float(sys.argv[1]) if len(sys.argv) > 1 else 2.2
vals = [round(255 * (i / 255) ** g) for i in range(256)]
print('/* generated by tools/gen_gamma.py, gamma = %.2f */' % g)
print('#include <stdint.h>')
print('const uint8_t gamma_lut[256] = {')
for i in range(0, 256, 16):
    print('    ' + ', '.join('%3d' % v for v in vals[i:i + 16]) + ',')
print('};')
