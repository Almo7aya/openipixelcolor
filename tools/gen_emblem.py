"""Generate firmware/src/app/emblem.c: THE FINALS emblem as pixel masks, rebuilt from the shape of the logo
(a rounded "A" made of three legs: a notch at the bottom centre and a diagonal gap parallel to the right
edge), supersampled 8x8 per pixel. Prints an ASCII preview of each size. For the fan-made animations in
firmware/src/app/fx_finals.c; THE FINALS and its emblem belong to Embark Studios.

usage: python tools/gen_emblem.py [--write]      (writes firmware/src/app/emblem.c)
"""
import sys
from pathlib import Path

SIZES = {"big": (28, 17), "small": (18, 11)}


def inside(u, v, gap=0.62):
    """u, v in emblem units: width 28, height 17 (apex at the top, base at v = 17).
    gap = half width of the diagonal gap in emblem units (about half an output pixel at every size)."""
    apex_y, slope = -1.6, 14.0 / 18.6
    if v < apex_y:
        return False
    if abs(u - 14.0) > (v - apex_y) * slope:
        return False
    if v < 0.9 and abs(u - 14.0) > 1.6 + v * 1.3:          # round the apex
        return False
    if v >= 11.3 and abs(u - 9.6) <= (v - 11.3) * slope:   # notch between the left and middle legs
        return False
    if v >= 6.8 and abs((u - 14.3) - (v - 6.8) * slope) < gap:   # gap between the middle and right legs
        return False
    return True


def mask(w, h, ss=8):
    rows = []
    for y in range(h):
        bits = []
        for x in range(w):
            n = sum(inside((x + (i + .5) / ss) * 28 / w, (y + (j + .5) / ss) * 17 / h, 0.58 * 28 / w)
                    for i in range(ss) for j in range(ss))
            bits.append(n * 2 >= ss * ss)
        rows.append(bits)
    return rows


def main():
    out = ["/* generated by tools/gen_emblem.py - do not edit */", '#include "emblem.h"', ""]
    for name, (w, h) in SIZES.items():
        rows = mask(w, h)
        print(f"{name} {w}x{h}")
        for r in rows:
            print("".join("#" if b else "." for b in r))
        vals = [sum(1 << (w - 1 - x) for x, b in enumerate(r) if b) for r in rows]
        out.append(f"const uint32_t emblem_{name}[{h}] = {{")
        out.append("    " + ", ".join(f"0x{v:07X}" for v in vals))
        out.append("};")
    if "--write" in sys.argv:
        p = Path(__file__).resolve().parent.parent / "firmware" / "src" / "app" / "emblem.c"
        p.write_text("\n".join(out) + "\n", encoding="utf-8")
        print("wrote", p)


main()
