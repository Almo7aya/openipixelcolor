"""Generate firmware/src/app/tables.c: sine table and per-pixel polar tables for the 32x32 panel.

  sin8[256]       : 128 + 127*sin(2*pi*i/256)            (0..255)
  ang32[32][32]   : atan2 around the panel centre, 0..255 == full turn
  dist32[32][32]  : distance from the centre in 1/8 pixel units (0..181)

usage: python gen_tables.py > ../firmware/src/app/tables.c
"""
import math

print('/* generated by tools/gen_tables.py - do not edit */')
print('#include "tables.h"')
print('const uint8_t sin8[256] = {')
v = [round(128 + 127 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
for i in range(0, 256, 16):
    print('    ' + ', '.join(f'{x:3d}' for x in v[i:i + 16]) + ',')
print('};')

c = 15.5
for name, fn in (('ang32', lambda dx, dy: round((math.atan2(dy, dx) / (2 * math.pi)) * 256) & 255),
                 ('dist32', lambda dx, dy: min(255, round(math.hypot(dx, dy) * 8)))):
    print(f'const uint8_t {name}[32][32] = {{')
    for y in range(32):
        row = [fn(x - c, y - c) for x in range(32)]
        print('    {' + ','.join(f'{x:3d}' for x in row) + '},')
    print('};')
