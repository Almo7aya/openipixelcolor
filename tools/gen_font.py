rows = [ln for ln in G.strip().splitlines()]
assert len(rows) == 95, len(rows)
print('/* generated by tools/gen_font.py - hand-drawn 5x7 font, ASCII 32..126 */')
print('#include "tables.h"')
print('const uint8_t font5x7[95][5] = {')
for i, ln in enumerate(rows):
    g = ln.split('|')
    assert len(g) == 7 and all(len(r) == 5 for r in g), (i, ln)
    cols = []
    for x in range(5):
        b = 0
        for y in range(7):
            if g[y][x] == '#':
                b |= 1 << y
        cols.append(b)
    ch = chr(32 + i)
    label = {'\\': 'backslash', "'": 'quote'}.get(ch, ch)
    print('    {' + ','.join(f'0x{c:02X}' for c in cols) + '},  /* ' + label + ' */')
print('};')
